/**
 * Baut aus schreibgeschützten Produktions-Exporten (matches/bets/combos/profiles/teams/players .json in $RECAP_DATA_DIR)
 * einen PSEUDONYMISIERTEN, VERSCHLÜSSELTEN Snapshot (AES-256-GCM) für die Datenbank-freie Winter-Recap-Vorschau.
 * Das Repo ist öffentlich: committet wird NUR die verschlüsselte Datei; der Schlüssel wird nie eingecheckt, sondern in
 * $RECAP_KEY_OUT (außerhalb des Repos) abgelegt. Entfernt: Benutzernamen, E-Mails, Kontostände, Avatare, Admin-Flags.
 *   RECAP_DATA_DIR=... RECAP_KEY_OUT=... node scripts/build-recap-snapshot.mjs
 */
import fs from 'node:fs'
import path from 'node:path'
import zlib from 'node:zlib'
import crypto from 'node:crypto'

const dir = process.env.RECAP_DATA_DIR
const keyOut = process.env.RECAP_KEY_OUT
if (!dir || !keyOut) throw new Error('RECAP_DATA_DIR und RECAP_KEY_OUT setzen')
const J = (n) => JSON.parse(fs.readFileSync(path.join(dir, n + '.json'), 'utf8'))
const matches = J('matches').filter((m) => m.match_date >= '2026-08-01')
const bets = J('bets').filter((b) => b.season === '26/27')
const combos = J('combos').filter((c) => c.season === '26/27')
const profilesAll = J('profiles')
const used = new Set([...bets.map((b) => b.user_id), ...combos.map((c) => c.user_id)])
const idMap = new Map()
const uid = (id) => { if (!idMap.has(id)) idMap.set(id, 'u' + String(idMap.size + 1).padStart(2, '0')); return idMap.get(id) }
const profiles = profilesAll.filter((p) => used.has(p.id)).map((p) => ({ id: uid(p.id), display_name: p.display_name, username: null, avatar_url: null, deleted_at: p.deleted_at ? 'deleted' : null }))
const snap = {
  version: 1, builtAt: new Date().toISOString(), source: 'Produktion, nur lesend',
  matches: matches.map(({ id, matchday, match_date, home_team_id, away_team_id, home_score, away_score, status, match_category, is_topspiel, tippspiel_matchday, competition_type, annulment_type, annulment_official_confirmed_at }) => ({ id, matchday, match_date, home_team_id, away_team_id, home_score, away_score, status, match_category, is_topspiel, tippspiel_matchday, competition_type, annulment_type, annulment_official_confirmed_at })),
  bets: bets.map((b) => ({ ...b, user_id: uid(b.user_id) })),
  combos: combos.map((c) => ({ ...c, user_id: uid(c.user_id) })),
  profiles,
  teams: J('teams'), players: J('players'),
}
const key = crypto.randomBytes(32), iv = crypto.randomBytes(12)
const c = crypto.createCipheriv('aes-256-gcm', key, iv)
const enc = Buffer.concat([c.update(zlib.gzipSync(JSON.stringify(snap))), c.final()])
const out = { v: 1, alg: 'aes-256-gcm', iv: iv.toString('base64'), tag: c.getAuthTag().toString('base64'), data: enc.toString('base64') }
fs.writeFileSync(path.join(process.cwd(), 'lib/recap/snapshot.enc.ts'), `// GENERATED by scripts/build-recap-snapshot.mjs – nur Chiffretext (AES-256-GCM), ohne Schlüssel nicht lesbar.\nexport const SNAPSHOT_ENC = ${JSON.stringify(out)}\n`)
fs.writeFileSync(keyOut, key.toString('hex'), { mode: 0o600 })
console.log('matches', snap.matches.length, 'bets', snap.bets.length, 'combos', snap.combos.length, 'profiles', profiles.length, 'bytes', enc.length)
